"""Generates lib/design_system/icons.dart with only the Phosphor icons the app
uses. Phosphor (MIT) is bundled as fonts in assets/fonts; the unmaintained
phosphor_flutter package is not used (it does not compile on current Flutter).

Run after using a new icon:  python tool/gen_icons.py
"""
import json, pathlib, re

root = pathlib.Path(__file__).resolve().parent.parent
codes = json.loads((root / 'tool' / 'phosphor_codepoints.json').read_text())
styles = {'Regular': 'regular', 'Fill': 'fill', 'Bold': 'bold'}
used = {s: set() for s in styles}
for path in (root / 'lib').rglob('*.dart'):
    for style, name in re.findall(r'PhosphorIcons(Regular|Fill|Bold)\.(\w+)', path.read_text(encoding='utf-8')):
        used[style].add(name)

lines = [
    '// GENERATED by tool/gen_icons.py. Do not edit by hand.',
    '// Phosphor Icons (MIT), bundled as fonts in assets/fonts.',
    '// ignore_for_file: public_member_api_docs',
    '',
    "import 'package:flutter/widgets.dart';",
    '',
]
missing = []
for style, key in styles.items():
    lines.append(f'abstract final class PhosphorIcons{style} {{')
    for name in sorted(used[style]):
        code = codes[key].get(name)
        if code is None:
            missing.append(f'{style}.{name}')
            continue
        lines.append(f"  static const {name} = IconData(0x{code:x}, fontFamily: 'Phosphor{style}');")
    lines.append('}')
    lines.append('')
(root / 'lib' / 'design_system' / 'icons.dart').write_text('\n'.join(lines), encoding='utf-8')
print('icons:', {s: len(v) for s, v in used.items()})
if missing:
    raise SystemExit('Unknown icons: ' + ', '.join(missing))
